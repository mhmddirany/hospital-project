-- Roadmap step 1: the first real database schema.
--
-- Flyway runs every V<n>__<description>.sql file in this folder exactly
-- once, in version order, and records it in flyway_schema_history. NEVER
-- edit this file after it has been run against a database you care about:
-- add a new V2__....sql with the change instead.
--
-- Written to run unchanged on PostgreSQL (development/production) and on
-- H2 in PostgreSQL mode (tests).

CREATE TABLE patients (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255)  NOT NULL,
    age        INTEGER       NOT NULL,
    email      VARCHAR(255),
    phone      VARCHAR(32),
    allergies  VARCHAR(1000)
);

-- Patient.medicalRecord.conditions / .medications (@ElementCollection)
CREATE TABLE patient_conditions (
    patient_id      INTEGER      NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    list_index      INTEGER      NOT NULL,
    condition_name  VARCHAR(255) NOT NULL,
    PRIMARY KEY (patient_id, list_index)
);

CREATE TABLE patient_medications (
    patient_id       INTEGER      NOT NULL REFERENCES patients (id) ON DELETE CASCADE,
    list_index       INTEGER      NOT NULL,
    medication_name  VARCHAR(255) NOT NULL,
    PRIMARY KEY (patient_id, list_index)
);

CREATE TABLE doctors (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    age           INTEGER      NOT NULL,
    specialty     VARCHAR(255) NOT NULL,
    availability  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE nurses (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    age           INTEGER      NOT NULL,
    department    VARCHAR(255) NOT NULL,
    availability  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE receptionists (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    age           INTEGER      NOT NULL,
    availability  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE appointments (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_time   TIMESTAMP   NOT NULL,
    status      VARCHAR(20) NOT NULL,
    patient_id  INTEGER     NOT NULL REFERENCES patients (id),
    doctor_id   INTEGER     NOT NULL REFERENCES doctors (id)
);

-- The lookups the application actually runs: a patient's appointments,
-- a doctor's schedule (and double-booking check), and tomorrow's reminders.
CREATE INDEX idx_appointments_patient ON appointments (patient_id);
CREATE INDEX idx_appointments_doctor_time ON appointments (doctor_id, date_time);
CREATE INDEX idx_appointments_time ON appointments (date_time);

CREATE TABLE users (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(100) NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20)  NOT NULL
);
